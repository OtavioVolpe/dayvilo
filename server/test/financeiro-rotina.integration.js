import test from 'node:test';
import assert from 'node:assert/strict';
import { criarPoolBanco } from '../src/db.js';
import { criarServicoFinanceiro } from '../src/servicos/financeiro.js';
import { criarServicoTarefas } from '../src/servicos/tarefas.js';
import { alterarSelecao } from '../src/servicos/selecao-tarefas.js';
import { obterDataHoje } from '../src/validacoes/tarefas.js';

test('Financeiro na Rotina: recorrência, pagamento, vencimento, remoção, conflitos e isolamento', async () => {
  const pool=criarPoolBanco(), c=await pool.getConnection();
  try {
    await c.beginTransaction();
    const [r]=await c.execute('INSERT INTO usuarios (nome) VALUES (?)',['Lembretes']);
    const [r2]=await c.execute('INSERT INTO usuarios (nome) VALUES (?)',['Outra conta']);
    const u={id:r.insertId,fuso_horario:'America/Sao_Paulo'}, outro={...u,id:r2.insertId};
    const f=criarServicoFinanceiro(c), t=criarServicoTarefas(c), hoje=obterDataHoje(u.fuso_horario);
    const ano=Number(hoje.slice(0,4))+1, dia=ano+'-01-10';
    const base={tipo:'despesa',descricao:'Academia',categoria:'Saúde',valor_centavos:9350,data_prevista:dia,data_pagamento:null,observacao:'',lembrar_rotina:true,horario_lembrete:'09:30'};
    await f.salvarLancamento(u,{...base,repetir_ate:ano+'-03-10'});
    let l=(await f.listar(u,{mes:ano+'-01'})).lancamentos[0];
    let tarefa=(await t.listar(u,{data:dia})).tarefas[0];
    assert.equal(tarefa.titulo,'Pagar Academia'); assert.equal(tarefa.financeiro_id,l.id); assert.equal(tarefa.horario,'09:30');
    assert.equal((await t.listar(u,{data:ano+'-02-10'})).tarefas.length,1);
    assert.equal((await t.listar(outro,{data:dia})).tarefas.length,0);
    await assert.rejects(f.consultarLancamento(outro,l.id),e=>e.status===404);
    await assert.rejects(t.concluir(u,{concluida:true},tarefa.id),e=>e.status===409);
    await assert.rejects(t.reagendar(u,{data_prevista:hoje},tarefa.id),e=>e.status===409);
    await assert.rejects(alterarSelecao(c,u.id,{data:dia,acao:'concluir',tarefas:[{id:tarefa.id,situacao:'pendente'}]}),e=>e.status===409);
    await f.situacao(u,l.id,{versao:l.versao,data_pagamento:hoje});
    assert.equal((await t.listar(u,{data:dia})).tarefas[0].situacao,'concluida');
    await assert.rejects(f.situacao(u,l.id,{versao:l.versao,data_pagamento:null}),e=>e.status===409);
    l=await f.consultarLancamento(u,l.id);
    await f.situacao(u,l.id,{versao:l.versao,data_pagamento:null});
    l=await f.consultarLancamento(u,l.id);
    await f.salvarLancamento(u,{...base,versao:l.versao,data_prevista:ano+'-01-12',horario_lembrete:'10:00'},l.id);
    assert.equal((await t.listar(u,{data:dia})).tarefas.length,0);
    tarefa=(await t.listar(u,{data:ano+'-01-12'})).tarefas[0];assert.equal(tarefa.horario,'10:00');assert.equal(tarefa.situacao,'pendente');
    l=await f.consultarLancamento(u,l.id);
    await t.excluir(u,{},tarefa.id);
    assert.equal((await f.consultarLancamento(u,l.id)).lembrar_rotina,false);
    await assert.rejects(f.salvarLancamento(u,{...base,versao:l.versao},l.id),e=>e.status===409);
    l=await f.consultarLancamento(u,l.id);
    await f.salvarLancamento(u,{...base,versao:l.versao,data_prevista:l.data_prevista,escopo:'proximos'},l.id);
    assert.equal((await t.listar(u,{data:ano+'-01-12'})).tarefas.length,1);
    l=await f.consultarLancamento(u,l.id);
    await f.excluirLancamento(u,l.id,{versao:l.versao,escopo:'proximos'});
    const [[resto]]=await c.execute('SELECT COUNT(*) AS n FROM tarefas WHERE usuario_id=?',[u.id]);assert.equal(resto.n,0);
    await f.salvarLancamento(u,{...base,lembrar_rotina:false});
    assert.equal((await t.listar(u,{data:dia})).tarefas.length,0);
    await assert.rejects(f.salvarLancamento(u,{...base,tipo:'receita'}),e=>e.status===400);
    await assert.rejects(f.salvarLancamento(u,{...base,horario_lembrete:'25:00'}),e=>e.status===400);
    await f.salvarLancamento(u,{...base,data_prevista:hoje,data_pagamento:hoje});
    let paga=(await f.listar(u,{mes:hoje.slice(0,7)})).lancamentos[0];
    assert.equal((await t.listar(u,{data:hoje})).tarefas[0].situacao,'concluida');
    await f.salvarLancamento(u,{...base,data_prevista:hoje,data_pagamento:hoje,versao:paga.versao,lembrar_rotina:false},paga.id);
    assert.equal((await t.listar(u,{data:hoje})).tarefas.length,0);
    assert.equal((await f.consultarLancamento(u,paga.id)).data_pagamento,hoje);
  } finally {await c.rollback();c.release();await pool.end();}
});
