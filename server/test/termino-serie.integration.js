import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { criarPoolBanco } from '../src/db.js';
import { criarAplicacao } from '../src/app.js';
import { criarRepositorioTarefas } from '../src/repositorios/tarefas.js';
import { obterDataHoje } from '../src/validacoes/tarefas.js';
import { criarServicoTarefas } from '../src/servicos/tarefas.js';
import { prepararSessaoTeste } from './sessao-fixture.js';

test('término: prolongar, encurtar, preservar histórico, dias semanais, legado e isolamento', async () => {
  const pool=criarPoolBanco(), banco=await pool.getConnection(); let servidor;
  try {
    await banco.beginTransaction();
    const [u]=await banco.execute('INSERT INTO usuarios(nome) VALUES (?)',['Término teste']);
    const [outro]=await banco.execute('INSERT INTO usuarios(nome) VALUES (?)',['Outro término']);
    const headers=await prepararSessaoTeste(banco,u.insertId);
    servidor=criarAplicacao({banco}).listen(0,'127.0.0.1'); await once(servidor,'listening');
    const url='http://127.0.0.1:'+servidor.address().port+'/api';
    const chamar=async(rota,method='GET',body)=>{const r=await fetch(url+rota,{method,headers,body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,dados:await r.json()};};
    const hoje=obterDataHoje('America/Sao_Paulo');
    const dia=n=>{const d=new Date(hoje+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+n);return d.toISOString().slice(0,10);};
    const repo=criarRepositorioTarefas(banco);
    const nova=await chamar('/tarefas/repetidas','POST',{tarefa:{titulo:'Rotina',data_prevista:dia(-1)},repeticao:{tipo:'diaria',ate:dia(3)}});
    assert.equal(nova.status,201);
    const id=nova.dados.tarefa.id, rota='/tarefas/'+id+'/serie';
    assert.equal((await chamar(rota)).dados.ate,dia(3));
    let ts=await repo.listarPeriodo(u.insertId,dia(-1),dia(8));
    await repo.definirSituacao(u.insertId,ts[1].id,'pulada');
    await repo.definirSituacao(u.insertId,ts[3].id,'concluida');
    await repo.definirSituacao(u.insertId,ts[4].id,'pulada');
    // Individually deleted occurrences inside the old period are not recreated.
    await repo.excluir(u.insertId,ts[2].id);
    let r=await chamar(rota,'PUT',{titulo:'Novo',horario:'07:30',ate:dia(5)});
    assert.equal(r.status,200,JSON.stringify(r.dados));assert.equal(r.dados.criadas,2);
    r=await chamar(rota,'PUT',{titulo:'Novo',ate:dia(5)});assert.equal(r.dados.criadas,0);
    ts=await repo.listarPeriodo(u.insertId,dia(-1),dia(8));
    assert.equal(ts.some(t=>t.data_prevista===dia(1)),false);
    assert.equal(ts.find(t=>t.data_prevista===hoje).titulo,'Rotina');
    r=await chamar(rota,'PUT',{titulo:'Curta',ate:dia(1)});
    assert.equal(r.status,200);assert.equal(r.dados.removidas,3);
    ts=await repo.listarPeriodo(u.insertId,dia(-1),dia(8));
    assert.deepEqual(ts.map(t=>t.data_prevista),[dia(-1),hoje,dia(2)]);
    assert.equal(ts.at(-1).situacao,'concluida');
    assert.equal((await chamar(rota,'PUT',{titulo:'Inválida',ate:dia(-1)})).status,400);
    assert.equal((await chamar(rota,'PUT',{titulo:'Inválida',ate:dia(366)})).status,400);
    const semana=await chamar('/tarefas/repetidas','POST',{tarefa:{titulo:'Semanal',data_prevista:dia(1)},repeticao:{tipo:'semanal',dias:[1,3],ate:dia(8)}});
    const rs='/tarefas/'+semana.dados.tarefa.id+'/serie';
    assert.equal((await chamar(rs,'PUT',{titulo:'Semanal',ate:dia(22)})).status,200);
    const semanaId=semana.dados.tarefa.serie_id;
    ts=(await repo.listarPeriodo(u.insertId,dia(1),dia(22))).filter(t=>t.serie_id===semanaId);
    assert.ok(ts.length>2);assert.ok(ts.every(t=>[1,3].includes(new Date(t.data_prevista+'T12:00:00Z').getUTCDay())));
    const antiga=await repo.criarRepetidas(u.insertId,{titulo:'Antiga',observacao:null,horario:null,prioridade:false},[hoje,dia(1)]);
    const ra='/tarefas/'+antiga.tarefa.id+'/serie';
    assert.equal((await chamar(ra)).dados.tipo,null);
    assert.equal((await chamar(ra,'PUT',{titulo:'Antiga',ate:dia(3)})).status,400);
    r=await chamar(ra,'PUT',{titulo:'Antiga',ate:dia(3),regra:{tipo:'diaria'}});
    assert.equal(r.status,200);assert.equal(r.dados.criadas,2);
    assert.equal((await chamar(ra)).dados.tipo,'diaria');
    const antesFalha=await repo.listarPeriodo(u.insertId,hoje,dia(30));
    let insercoes=0;
    const falhando={query:banco.query.bind(banco),execute:async(sql,params)=>{if(sql.startsWith('INSERT INTO tarefas') && ++insercoes===2)throw new Error('Falha simulada');return banco.execute(sql,params);}};
    await assert.rejects(criarServicoTarefas(falhando).editarSerie({id:u.insertId,fuso_horario:'America/Sao_Paulo'},{titulo:'Não gravar',ate:dia(6)},antiga.tarefa.id),/Falha simulada/);
    assert.deepEqual(await repo.listarPeriodo(u.insertId,hoje,dia(30)),antesFalha);
    assert.equal((await chamar(ra)).dados.ate,dia(3));
    const privada=await repo.criarRepetidas(outro.insertId,{titulo:'Privada',observacao:null,horario:null,prioridade:false},[hoje]);
    assert.equal((await chamar('/tarefas/'+privada.tarefa.id+'/serie')).status,404);
    assert.equal((await chamar('/tarefas/'+privada.tarefa.id+'/serie','PUT',{titulo:'Não',ate:dia(3)})).status,404);
  } finally {if(servidor){servidor.closeAllConnections();await new Promise(r=>servidor.close(r));}await banco.rollback();banco.release();await pool.end();}
});
