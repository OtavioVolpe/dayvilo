import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { criarPoolBanco } from '../src/db.js';
import { criarAplicacao } from '../src/app.js';
import { criarServicoAutenticacao } from '../src/servicos/autenticacao.js';
import { criarServicoAlteracaoEmail } from '../src/servicos/alteracao-email.js';
import { criarServicoConfirmacao } from '../src/servicos/confirmacao-email.js';
import { criarServicoMinhaConta } from '../src/servicos/minha-conta.js';
import { criarServicoRecuperacao } from '../src/servicos/recuperacao-senha.js';

test('troca de e-mail preserva dados, exige senha e confirmação e invalida acessos antigos', async () => {
  assert.ok(['127.0.0.1', 'localhost'].includes(process.env.MYSQL_HOST), 'Use somente banco descartável local');
  const pool = criarPoolBanco(), banco = await pool.getConnection(); let servidor;
  try {
    await banco.beginTransaction();
    const mensagens = []; let falhar = false;
    const config = { banco, urlAplicacao: 'http://127.0.0.1:5173/', enviarEmail: async m => { if (falhar) throw Error('simulada'); mensagens.push(m); } };
    const contas = criarServicoAutenticacao(banco), troca = criarServicoAlteracaoEmail(config), confirmacao = criarServicoConfirmacao(config);
    const email = `${randomUUID()}@example.test`, novo = `novo-${email}`, senha = 'Uma senha longa para testar 1!';
    let sessao = await contas.cadastrar({ nome: 'Teste', email, senha });
    const usuario = await contas.consultar(sessao.token);
    await banco.execute('INSERT INTO tarefas (usuario_id,titulo) VALUES (?,?)', [usuario.id, 'Preservar tarefa']);
    const [tarefas] = await banco.execute('SELECT * FROM tarefas WHERE usuario_id=?', [usuario.id]);
    await confirmacao.solicitar(usuario.id);
    const antigo = mensagens.at(-1).texto.match(/#confirmar-email=([a-f0-9]{64})/)[1];
    const pedir = (destino = novo, senhaAtual = senha) => troca.solicitar(usuario.id, sessao.token, { email: destino, senha_atual: senhaAtual });
    const token = () => mensagens.at(-1).texto.match(/#alterar-email=([a-f0-9]{64})/)[1];
    await assert.rejects(pedir(novo, 'errada'), { status: 400 });
    falhar = true; await assert.rejects(pedir(), { status: 503 }); falhar = false;
    assert.equal((await troca.consultar(usuario.id)).pendente, null);
    await pedir(); const primeiro = token();
    assert.equal((await contas.consultar(sessao.token)).email, email);
    assert.equal((await troca.consultar(usuario.id)).pendente, novo);
    await assert.rejects(confirmacao.confirmar({ token: antigo }), { status: 400 });
    await assert.rejects(confirmacao.solicitar(usuario.id), { status: 409 });
    await assert.rejects(pedir(), { status: 429 });
    const outra = await contas.cadastrar({ nome: 'Outra', email: `outra-${email}`, senha });
    const outroUsuario = await contas.consultar(outra.token);
    assert.equal((await troca.consultar(outroUsuario.id)).pendente, null);
    await troca.cancelar(outroUsuario.id);
    assert.equal((await troca.consultar(usuario.id)).pendente, novo);
    await troca.cancelar(usuario.id);
    await assert.rejects(troca.confirmar({ token: primeiro }), { status: 400 });
    await assert.rejects(pedir(`outra-${email}`), { status: 409 });
    await pedir(); const expirado = token();
    await banco.execute('UPDATE alteracoes_email SET expira_em=DATE_SUB(UTC_TIMESTAMP(), INTERVAL 1 SECOND), criado_em=DATE_SUB(UTC_TIMESTAMP(), INTERVAL 2 MINUTE)');
    await assert.rejects(troca.confirmar({ token: expirado }), { status: 400 });
    await pedir(); const valido = token();
    await assert.rejects(troca.confirmar({ token: expirado }), { status: 400 });
    const recuperacao = criarServicoRecuperacao(config);
    await recuperacao.solicitar({ email });
    const recuperar = mensagens.at(-1).texto.match(/#redefinir-senha=([a-f0-9]{64})/)[1];
    servidor = criarAplicacao(config).listen(0, '127.0.0.1'); await once(servidor, 'listening');
    const url = `http://127.0.0.1:${servidor.address().port}/api/contas`;
    const post = (rota, dados, headers = {}) => fetch(url + rota, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Dayvilo': '1', ...headers }, body: JSON.stringify(dados) });
    assert.equal((await post('/email', {})).status, 401);
    assert.equal((await post('/email', {}, { Cookie: `dayvilo_sessao=${sessao.token}` })).status, 403);
    assert.equal((await post('/email/confirmar', { token: valido }, { 'X-Dayvilo': '' })).status, 403);
    assert.equal((await post('/email/confirmar', { token: valido })).status, 200);
    await assert.rejects(troca.confirmar({ token: valido }), { status: 400 });
    await assert.rejects(recuperacao.validar({ token: recuperar }), { status: 400 });
    assert.equal(await contas.consultar(sessao.token), null);
    await assert.rejects(contas.entrar({ email, senha }), { status: 401 });
    sessao = await contas.entrar({ email: novo, senha });
    const atualizado = await contas.consultar(sessao.token);
    assert.equal(atualizado.id, usuario.id); assert.equal(atualizado.email_confirmado, true);
    assert.deepEqual((await banco.execute('SELECT * FROM tarefas WHERE usuario_id=?', [usuario.id]))[0], tarefas);
    const quantidade = mensagens.length;
    await pedir(`final-${email}`); const canceladoPorSenha = token();
    assert.equal(mensagens.length, quantidade + 2); assert.equal(mensagens.at(-2).para, novo);
    await criarServicoMinhaConta(banco).senha(usuario.id, sessao.token, { senha_atual: senha, nova_senha: 'Outra senha longa para testar 2!' });
    await assert.rejects(troca.confirmar({ token: canceladoPorSenha }), { status: 400 });
  } finally {
    if (servidor) { servidor.closeAllConnections(); await new Promise(r => servidor.close(r)); }
    await banco.rollback(); banco.release(); await pool.end();
  }
});
